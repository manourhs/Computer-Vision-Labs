import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_blobs
from sklearn.cluster import KMeans
from skimage import data

X, y = make_blobs(

    n_samples=1000,

    centers=4,

    random_state=42

)

plt.figure(figsize=(8, 6))

plt.scatter(X[:, 0], X[:, 1], c="gray", s=20)

plt.title("Generated Data Before K-Means")

plt.xlabel("Feature 1")

plt.ylabel("Feature 2")

plt.savefig("kmeans_data_before.png")

plt.show()

kmeans = KMeans(

    n_clusters=4,

    random_state=42,

    n_init=10

)

labels = kmeans.fit_predict(X)

plt.figure(figsize=(8, 6))

plt.scatter(

    X[:, 0],

    X[:, 1],

    c=labels,

    cmap="viridis",

    s=20

)

centers = kmeans.cluster_centers_

plt.scatter(

    centers[:, 0],

    centers[:, 1],

    c="red",

    marker="X",

    s=200,

    label="Cluster Centers"

)

plt.title("Generated Data After K-Means")

plt.xlabel("Feature 1")

plt.ylabel("Feature 2")

plt.legend()

plt.savefig("kmeans_data_after.png")

plt.show()

coffee_image = data.coffee()

plt.figure(figsize=(8, 6))

plt.imshow(coffee_image)

plt.title("Coffee Image Before K-Means")

plt.axis("off")

plt.savefig("kmeans_image_before.png")

plt.show()

pixels = coffee_image.reshape(-1, 3)

kmeans_image = KMeans(

    n_clusters=4,

    random_state=42,

    n_init=10

)

pixel_labels = kmeans_image.fit_predict(pixels)

cluster_colors = kmeans_image.cluster_centers_

segmented_pixels = cluster_colors[pixel_labels]

segmented_image = segmented_pixels.reshape(

    coffee_image.shape

).astype(np.uint8)

plt.figure(figsize=(8, 6))

plt.imshow(segmented_image)

plt.title("Coffee Image After K-Means")

plt.axis("off")

plt.savefig("kmeans_image_after.png")

plt.show()